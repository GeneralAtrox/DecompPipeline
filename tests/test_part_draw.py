"""game.json part_draw (port/tools/part_draw.py): the key checked, and the PartDraw_ADDR wrapper gen_port adds, which
brackets the game's per-part 3D draw with port_part_begin and _end (pvr/pvr_parts.c). Synthetic; no game workspace.
Run: python -W error -m unittest tests.test_part_draw
"""
import pathlib
import sys
import unittest

TOOL = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOL / "port" / "tools"))
sys.path.insert(0, str(TOOL / "tests"))
sys.path.insert(0, str(TOOL))

import tempfile  # noqa: E402
import game_config  # noqa: E402
import gen_port  # noqa: E402
import part_draw  # noqa: E402
from test_sync import TMP  # noqa: E402,F401  (sets DECOMP_PROJECT when run alone)
from core import readable  # noqa: E402

E = game_config.ConfigError
PROTOS = {"8c02e07c": "void Fx_DrawPart(GameObj *obj, ModelPart *part);", "8c02e100": "u32 Fx_Count(GameObj *obj, s32 n);",
          "8c02e200": "s32 Fx_Pick(GameObj *obj, ModelPart *part, s32 n);"}


class PartDraw(unittest.TestCase):
    def test_config(self):
        self.assertIsNone(part_draw.config(None, {}, {}, None, E))
        self.assertEqual(part_draw.config({"function": "8C02E07C", "stamp": "0x24", "world": "0x28"}, {}, {}, None, E),
                         {"function": "8c02e07c", "stamp": 0x24, "world": 0x28})
        good = {"function": "8c02e07c", "stamp": "0x24", "world": "0x28"}
        for raw, wrap, wide in (({"function": "8c02e07c"}, {}, None), ({**good, "function": "8c02e0"}, {}, None),
                                ({**good, "world": "40"}, {}, None), ({**good, "stamp": 36}, {}, None),
                                (good, {}, {"functions": ["8c02e07c"]})):
            with self.subTest(raw=raw, wrap=wrap, wide=wide), self.assertRaises(E):
                part_draw.config(raw, wrap, {}, wide, E)
        with self.assertRaises(E):  # a hardware function is no draw to put inside a part
            part_draw.config(good, {}, {"8c02e07c": "hw"}, None, E)
        with self.assertRaises(E):  # ... also when the game wraps it too
            part_draw.config(good, {"8c02e07c": "Fx_Wrap"}, {}, {"functions": ["8c02e07c"]}, E)

    def test_wrapper(self):
        self.assertIsNone(part_draw.c_text(readable, None, PROTOS, gen_port.wrapper_proto))
        text, wraps = part_draw.c_text(readable, {"function": "8c02e07c", "stamp": 0x24, "world": 0x28}, PROTOS,
                                       gen_port.wrapper_proto)
        self.assertEqual(wraps, {"8c02e07c": "PartDraw_8c02e07c"})
        self.assertIn("void PartDraw_8c02e07c(GameObj *obj, ModelPart *part)\n{\n"
                      "    port_part_begin(obj, part, 0x24u, 0x28u, NULL);\n    Fx_DrawPart(obj, part);\n"
                      "    port_part_end(NULL);\n}\n", text)
        text, _ = part_draw.c_text(readable, {"function": "8c02e200", "stamp": 0x24, "world": 0x28}, PROTOS,
                                   gen_port.wrapper_proto)
        self.assertIn("    s32 part_result = Fx_Pick(obj, part, n);\n    port_part_end(NULL);\n    return part_result;\n", text)
        for addr in ("8c02e100", "8c02e300"):  # the second argument is no pointer; no function there
            with self.subTest(addr=addr), self.assertRaises(SystemExit):
                part_draw.c_text(readable, {"function": addr, "stamp": 0, "world": 0}, PROTOS, gen_port.wrapper_proto)


    def test_list_and_part_alone(self):  # Toy Commander: MeshNode_Draw(node, mode) and its prelit twin, the node its own object
        protos = {**PROTOS, "8c05d42c": "u32 MeshNode_Draw(MeshNode *node, u32 mode);",
                  "8c05d386": "u32 MeshNode_DrawPrelit(MeshNode *node, u32 mode);"}
        raw = {"function": ["8C05D42C", "8c05d386"], "stamp": "0x34", "world": "0x0", "part": "object"}
        cfg = part_draw.config(raw, {}, {}, None, E)
        self.assertEqual(cfg, {"function": ["8c05d42c", "8c05d386"], "stamp": 0x34, "world": 0, "part": "object"})
        for bad in ({**raw, "part": "first"}, {**raw, "function": []}, {**raw, "function": ["8c05d42c", "8C05D42C"]},
                    {**raw, "function": ["8c05d42c", 5]}, {**raw, "spare": "1"}):
            with self.subTest(raw=bad), self.assertRaises(E):
                part_draw.config(bad, {}, {}, None, E)
        text, wraps = part_draw.c_text(readable, cfg, protos, gen_port.wrapper_proto)
        self.assertEqual(wraps, {"8c05d42c": "PartDraw_8c05d42c", "8c05d386": "PartDraw_8c05d386"})
        self.assertIn("    port_part_begin(node, node, 0x34u, 0x0u, NULL);\n    u32 part_result = MeshNode_Draw(node, mode);\n", text)
        self.assertIn("MeshNode_DrawPrelit(node, mode);", text)
        self.assertEqual(text.count("Generated by"), 1)
        with self.assertRaises(SystemExit):  # the part alone must still be a pointer
            part_draw.c_text(readable, {**cfg, "function": "8c02e100"}, {**protos, "8c02e100": "u32 F(s32 n, u32 m);"},
                             gen_port.wrapper_proto)
    def test_a_wrapped_function_keeps_the_games_wrap_inside_the_part(self):  # Toy Commander: the boss copy relights MeshNode_Draw
        protos = {**PROTOS, "8c05d42c": "u32 MeshNode_Draw(MeshNode *node, u32 mode);",
                  "8c05d386": "u32 MeshNode_DrawPrelit(MeshNode *node, u32 mode);"}
        raw = {"function": ["8c05d42c", "8c05d386"], "stamp": "0x34", "world": "0x0", "part": "object"}
        wrap = {"8c05d42c": "GuestScene_MeshNodeDraw", "8c01937c": "FrameInterp_DrawViewports"}
        cfg = part_draw.config(raw, wrap, {}, None, E)  # accepted: composed, not refused
        text, wraps = part_draw.c_text(readable, cfg, protos, gen_port.wrapper_proto, wrap)
        self.assertEqual(wraps, {"8c05d42c": "PartDraw_8c05d42c", "8c05d386": "PartDraw_8c05d386"})  # the part wrapper takes the address
        self.assertIn("\nu32 GuestScene_MeshNodeDraw(MeshNode *node, u32 mode);\n\nu32 PartDraw_8c05d42c(MeshNode *node, u32 mode)\n{\n"
                      "    port_part_begin(node, node, 0x34u, 0x0u, NULL);\n    u32 part_result = GuestScene_MeshNodeDraw(node, mode);\n"
                      "    port_part_end(NULL);\n    return part_result;\n}\n", text)
        self.assertNotIn("= MeshNode_Draw(", text)  # never past the game's wrap
        self.assertIn("    u32 part_result = MeshNode_DrawPrelit(node, mode);\n", text)  # the unwrapped twin as before
        with tempfile.TemporaryDirectory(dir=TMP) as d:  # write(): the address goes to the part wrapper, the other wraps stay
            got, _ = part_draw.write(pathlib.Path(d), readable, {"part_draw": cfg}, protos, gen_port.wrapper_proto,
                                     lambda p, s: p.write_text(s, encoding="utf-8"), wrap, [])
            self.assertEqual(got, {**wrap, "8c05d42c": "PartDraw_8c05d42c", "8c05d386": "PartDraw_8c05d386"})
            self.assertIn("GuestScene_MeshNodeDraw(node, mode);", (pathlib.Path(d) / "part_draw.c").read_text(encoding="utf-8"))

    def test_lists(self):  # Toy Commander: the live positions in r14 and its own table, given to Kamui only per pass
        protos = {**PROTOS, "8c05d42c": "u32 MeshNode_Draw(MeshNode *node, u32 mode);"}
        lists = {"table": "8c0fce04", "current": "8C1128A8", "register": "r14", "offsets": ["0x0", "0xc", "0x4", "0x10", "0x8"]}
        raw = {"function": "8c05d42c", "stamp": "0x34", "world": "0x0", "part": "object", "lists": lists}
        cfg = part_draw.config(raw, {}, {}, None, E)
        self.assertEqual(cfg["lists"], {"table": 0x8c0fce04, "current": 0x8c1128a8, "register": 14,
                                        "offsets": [0, 0xc, 4, 0x10, 8]})
        for bad in ({**lists, "register": "r15"}, {**lists, "register": "r7"}, {**lists, "offsets": ["0x0"] * 4},
                    {**lists, "table": "8c0fce"}, {**lists, "spare": 1}, {**lists, "offsets": ["0x0", 4, "0x4", "0x10", "0x8"]}):
            with self.subTest(lists=bad), self.assertRaises(E):
                part_draw.config({**raw, "lists": bad}, {}, {}, None, E)
        text, _ = part_draw.c_text(readable, cfg, protos, gen_port.wrapper_proto)
        self.assertIn("static const u32 off[5] = {0x0u, 0xcu, 0x4u, 0x10u, 0x8u};", text)
        self.assertIn("u32 cur = *(const u32 *)(uintptr_t)guest_fold(0x8c1128a8u) & 0x1fffffffu;", text)
        self.assertIn("at[l] = cur == (entry & 0x1fffffffu) ? port_sh4_gs[6] : *(const u32 *)(uintptr_t)guest_fold(entry);",
                      text)
        self.assertIn("{\n    u32 part_at[5];\n    port_part_begin(node, node, 0x34u, 0x0u, part_lists(part_at));\n"
                      "    u32 part_result = MeshNode_Draw(node, mode);\n    port_part_end(part_lists(part_at));\n", text)


if __name__ == "__main__":
    unittest.main()
