/* Fills every index whose top bits are the code: an index's entry is the code it starts with. Unused entries keep
 * length 0 (an invalid code). */
static void build(MpvVlc *t, u32 bits, const Code *c, u32 n)
{
    memset(t, 0, sizeof *t << bits);
    for (u32 i = 0; i < n; i++) {
        u32 v = 0, len = 0;
        for (const char *p = c[i].bits; *p; p++) v = v << 1 | (u32)(*p == '1'), len++;
        for (u32 k = 0; k < 1u << (bits - len); k++) {
            t[v << (bits - len) | k].value = c[i].value;
            t[v << (bits - len) | k].len = (u8)len;
        }
    }
}

#define BUILD(t, bits, c) build(t, bits, c, sizeof c / sizeof c[0])
void mpv_tables_init(void)
{
    static int done;
    if (done) return;
    done = 1;
    BUILD(g_mpv_mbai, 11, kMbai);
    BUILD(g_mpv_mb_i, 2, kMbI);
    BUILD(g_mpv_mb_p, 6, kMbP);
    BUILD(g_mpv_mb_b, 6, kMbB);
    BUILD(g_mpv_cbp, 9, kCbp);
    BUILD(g_mpv_motion, 10, kMotion);
    BUILD(g_mpv_dc_y, 7, kDcY);
    BUILD(g_mpv_dc_c, 8, kDcC);
    BUILD(g_mpv_dct, 16, kDct);
}
