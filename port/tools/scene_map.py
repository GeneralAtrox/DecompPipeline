"""The scene dump's per-game map (runtime/scene_dump.h): <game>/scene_dump.json, turned into build/gen/scene_map.c by
gen_port.py. Without the file the tables are empty and a dump has the kit's fields only.

    {
      "root": "..",                      the folder the file paths below are relative to (from the game folder)
      "fields": [                        guest values, by the global's name in game.h (the compiler checks it)
        {"key": "scene", "global": "g_scenePath"},                     a char array is a string
        {"key": "menu", "global": "g_menuSeqState", "enum_prefix": "MENU_SEQ_"},   names from the readable headers
        {"key": "mode", "global": "g_gameMode", "names": {"2": "GAME_MODE_PLAYER_VIEWS"}},
        {"key": "speed", "global": "g_player", "deref": [64], "type": "f32"},   read the pointer, add 64, read an f32
        {"key": "life{i}", "expr": "g_fighters[{i}].obj.life", "type": "f32", "index": 4, "log": true}
                                         a member of a global (the compiler checks the names); "index": N makes N fields,
                                         {i} 0..N-1 in key and expr; "log": true puts a line in the game log (game_log.h)
                                         whenever the value changes (every field is in its periodic snapshot)
      ],
      "counts": [{"key": "fighters", "of": ["active0", "active1"]}],   how many of those fields are not zero
      "log_every": 600,                  the game log's snapshot interval in vertical blanks (the kit's default: 600)
      "task": ["scene", "menu"],         the fields the one-line task names
      "read_always": ["port/README.md"],
      "rules": [{"key": "mode", "values": [2], "read": ["..."], "edit": ["..."]}]   (key left out: always)
    }
"""
import json
import pathlib
import re

BASE = {"s8": (1, "SCENE_INT"), "s16": (2, "SCENE_INT"), "s32": (4, "SCENE_INT"), "int": (4, "SCENE_INT"),
        "u8": (1, "SCENE_UINT"), "u16": (2, "SCENE_UINT"), "u32": (4, "SCENE_UINT"), "f32": (4, "SCENE_FLOAT"),
        "float": (4, "SCENE_FLOAT"), "f64": (8, "SCENE_FLOAT"), "double": (8, "SCENE_FLOAT")}


def c_string(s):
    return json.dumps(s)  # a JSON string is a valid C string literal for the text used here


def kind_of(ctype, where):
    """(size, kind) for a type: a base type, a pointer (its address), or char[N] (a string)."""
    t = ctype.strip()
    m = re.fullmatch(r"char\s*\[\s*(0x[0-9a-fA-F]+|\d+)\s*\]", t)
    if m:
        return int(m[1], 0), "SCENE_STRING"
    if t.endswith("*"):
        return 4, "SCENE_UINT"
    t = re.sub(r"\b(const|volatile|unsigned|signed)\b", "", t).strip() or "int"
    if t in BASE:
        return BASE[t]
    raise SystemExit(f"scene_dump.json {where}: type {ctype!r} is not a number or char array: give \"type\"")


def global_types(game_h):
    """{name: C type} from game.h's `typedef T rdg_NAME_t[N];` lines (N kept as a char[N] suffix)."""
    out = {}
    for m in re.finditer(r"^typedef (.+?) rdg_(\w+)_t(\[[^\]]+\])?;$", game_h, re.M):
        out[m[2]] = m[1] + (m[3] or "")
    return out


def header_names(include_dir, prefix):
    """{value: name} from `#define PREFIX_X n` and `PREFIX_X = n,` in the readable headers."""
    names = {}
    pat = re.compile(rf"(?:#define\s+({re.escape(prefix)}\w+)\s+\(?(-?(?:0x[0-9a-fA-F]+|\d+))u?\)?\s*(?:/[*/].*)?$"
                     rf"|^\s*({re.escape(prefix)}\w+)\s*=\s*(-?(?:0x[0-9a-fA-F]+|\d+))\s*,?)", re.M)
    for h in sorted(pathlib.Path(include_dir).rglob("*.h")):
        for m in pat.finditer(h.read_text(encoding="utf-8", errors="replace")):
            name, value = (m[1], m[2]) if m[1] else (m[3], m[4])
            names.setdefault(int(value, 0), name)
    if not names:
        raise SystemExit(f"scene_dump.json: no {prefix}* names in {include_dir}")
    return names


def expand(fields):
    """A field with "index": N is N fields: {i} in its key and expr is 0..N-1."""
    out = []
    for f in fields:
        if "index" not in f:
            out.append(f)
            continue
        for i in range(int(f["index"])):
            g = {k: (v.replace("{i}", str(i)) if isinstance(v, str) else v) for k, v in f.items() if k != "index"}
            out.append(g)
    return out


def scene_map_c(cfg, game_h, include_dir, header="game.h"):
    path = cfg["dir"] / "scene_dump.json"
    m = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
    m["fields"] = expand(m.get("fields", []))
    types = global_types(game_h)
    root = (cfg["dir"] / m.get("root", ".")).resolve()
    lines = ["/* Generated by port/tools/gen_port.py from scene_dump.json: the scene dump's map (runtime/scene_dump.h). */",
             f'#include "{header}"' if header else "", '#include "scene_dump.h"', ""]
    rows = []
    for i, f in enumerate(m.get("fields", [])):
        key = f["key"]
        if "addr" in f:  # a console without named globals (a Saturn): the guest address itself, the type given
            g, addr, ctype = None, f"(const void *)0x{int(f['addr'], 0):08x}u", f.get("type")
            if not ctype:
                raise SystemExit(f"scene_dump.json field {key}: \"addr\" takes \"type\"")
        elif "expr" in f:  # a member of a global: its address, the type given
            g = re.match(r"[A-Za-z_]\w*", f["expr"])[0]
            addr, ctype = f"&({f['expr']})", f.get("type")
            if g not in types or not ctype or "deref" in f:
                raise SystemExit(f"scene_dump.json field {key}: \"expr\" starts with a global of game.h, takes \"type\" "
                                 "and no \"deref\"")
        else:
            g = f["global"]
            addr, ctype = f"&{g}", None
        if g is not None and g not in types:
            raise SystemExit(f"scene_dump.json field {key}: no global {g} in game.h")
        deref = f.get("deref", [])
        size, kind = kind_of(ctype or f.get("type") or ("u32" if deref else types[g]), key)  # (an "addr" field always has a type)
        names = {int(k): v for k, v in f.get("names", {}).items()}
        if "enum_prefix" in f:
            names = {**header_names(include_dir, f["enum_prefix"]), **names}
        nref, dref = "NULL", "NULL"
        if names:
            lines.append(f"static const SceneName names_{i}[] = {{" +
                         ", ".join(f"{{{v}, {c_string(n)}}}" for v, n in sorted(names.items())) + "};")
            nref = f"names_{i}"
        if deref:
            lines.append(f"static const s32 deref_{i}[] = {{{', '.join(str(int(d)) for d in deref)}}};")
            dref = f"deref_{i}"
        if g is not None and "type" in f and "expr" not in f and not deref and kind_of(types[g], key)[0] < size:
            raise SystemExit(f"scene_dump.json field {key}: {f['type']} is larger than {g}")
        rows.append(f"    {{{c_string(key)}, {addr}, {dref}, {len(deref)}, {size}, {kind}, {nref}, {len(names)}, "
                    f"{1 if f.get('log') else 0}}},")
    keys = {f["key"] for f in m.get("fields", [])}
    if len(keys) != len(m.get("fields", [])):
        raise SystemExit("scene_dump.json: two fields have the same key")
    for k in m.get("task", []) + [r["key"] for r in m.get("rules", []) if "key" in r]:
        if k not in keys:
            raise SystemExit(f"scene_dump.json: {k} is not a field")
    rules = ([{"read": m["read_always"]}] if m.get("read_always") else []) + m.get("rules", [])
    lines += ["", "const SceneField scene_fields[] = {"] + (rows or ["    {0},"]) + ["};",
              f"const u32 scene_field_count = {len(rows)};", ""]
    crow = []
    for i, c in enumerate(m.get("counts", [])):
        missing = [k for k in c["of"] if k not in keys]
        if missing or c["key"] in keys:
            raise SystemExit(f"scene_dump.json count {c['key']}: {missing or 'the key is a field'} unknown")
        lines.append(f"static const char *const count_{i}[] = {{" + ", ".join(c_string(k) for k in c["of"]) + "};")
        crow.append(f"    {{{c_string(c['key'])}, count_{i}, {len(c['of'])}}},")
    lines += ["const SceneCount scene_counts[] = {"] + (crow or ["    {0},"]) + ["};",
              f"const u32 scene_count_count = {len(crow)};", f"const u32 scene_log_every = {int(m.get('log_every', 0))};", ""]
    lines.append("const char *const scene_task_keys[] = {" +
                 ", ".join(c_string(k) for k in m.get("task", []) or [""]) + "};")
    lines += [f"const u32 scene_task_count = {len(m.get('task', []))};", ""]
    out = []
    for i, r in enumerate(rules):
        for part in ("read", "edit", "values"):
            items = r.get(part, [])
            if items:
                ctype = "s32" if part == "values" else "char *const"
                vals = ", ".join(str(int(v)) if part == "values" else c_string(v) for v in items)
                lines.append(f"static const {ctype} rule{i}_{part}[] = {{{vals}}};")
        ref = {p: (f"rule{i}_{p}" if r.get(p) else "NULL") for p in ("read", "edit", "values")}
        key = c_string(r["key"]) if "key" in r else "NULL"
        out.append(f"    {{{key}, {ref['values']}, {len(r.get('values', []))}, {ref['read']}, {ref['edit']}, "
                   f"{len(r.get('read', []))}, {len(r.get('edit', []))}}},")
    lines += ["", "const SceneRule scene_rules[] = {"] + (out or ["    {0},"]) + ["};",
              f"const u32 scene_rule_count = {len(out)};", f"const char scene_root[] = {c_string(str(root))};", ""]
    return "\n".join(lines)
