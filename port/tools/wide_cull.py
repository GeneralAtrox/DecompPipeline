"""The wide view's model cull (game.json wide_cull, gen_port.py): a WideCull_ADDR wrapper per listed function.

A renderer that drops a model or part outside the viewport's rectangle culls against the 640x480 screen, so in a wider
frame the parts past the old edge go missing. Each wrapper calls its function with a viewport centred on the screen
grown by the frame's share for the call (port_wide_cull_begin and _end, base/present.c), and gen_port wraps the address
as game.json wrap would. At 4:3, or with a view off centre (a split screen, a picture-in-picture), the call is unchanged.

Nearest existing: gen_port.py - writes the game's generated files and takes game.json wrap, but it sits at the 400-line cap.
"""
import part_draw


def c_text(readable, wide_cull, protos, wrapper_proto):
    """(the C of the wrappers, {addr: wrapper}) for game.json wide_cull {"viewport", "functions"}, or None."""
    if not wide_cull:
        return None
    vp = f"0x{wide_cull['viewport']}u"
    text = ["/* Generated by port/tools/gen_port.py from game.json wide_cull: do not edit. */", '#include "game.h"',
            '#include "platform.h"', ""]
    wraps = {}
    for x in wide_cull["functions"]:
        if x not in protos:
            raise SystemExit(f"game.json wide_cull {x}: no function the port declares there")
        if readable.is_variadic(protos[x]):
            raise SystemExit(f"game.json wide_cull {x}: a variadic function cannot be wrapped")
        ret, name, params = readable.parse_proto(protos[x])
        wraps[x] = f"WideCull_{x}"
        call = f"{name}({', '.join(n for _, n in params)});"
        void = ret.strip() == "void"
        text += [wrapper_proto(protos[x], name, wraps[x])[:-1], "{", "    f32 wide_saved[4];",
                 f"    int wide = port_wide_cull_begin({vp}, wide_saved);",
                 f"    {call}" if void else f"    {ret} wide_result = {call}",
                 "    if (wide) {", f"        port_wide_cull_end({vp}, wide_saved);", "    }"]
        text += [] if void else ["    return wide_result;"]
        text += ["}", ""]
    return "\n".join(text), wraps


def write(out, readable, cfg, protos, wrapper_proto, write_if_changed):
    """game.json wrap and sources with the wrappers added: out/wide_cull.c is written, or removed when none is asked; then
    part_draw.py's wrapper (gen_port.py sits at the 400-line cap, so the generated wrappers are added here)."""
    wrap, sources = dict(cfg["wrap"]), list(cfg["sources"])
    got = c_text(readable, cfg.get("wide_cull"), protos, wrapper_proto)
    if got:
        write_if_changed(out / "wide_cull.c", got[0])
        wrap.update(got[1])
        sources.append(out / "wide_cull.c")
    elif (out / "wide_cull.c").exists():
        (out / "wide_cull.c").unlink()
    return part_draw.write(out, readable, cfg, protos, wrapper_proto, write_if_changed, wrap, sources)  # game.json part_draw
