"""New head types in the game's own part choice (game.json heads, port/saturn/sat_heads.c), for gen_saturn.py's sat_game.h.

Nearest existing: gen_saturn_menus.py and gen_saturn.py's team_fight_h - the same game.json section to #define lines;
gen_saturn.py is at its size limit and gen_saturn_menus.py is the menus' own (another card edits it), so heads have theirs.
part_choice_h, the versions heads stand on, came here from gen_saturn.py unchanged, for the same limit.
"""
import base64
import json
import struct
import sys

SLOT = 0x2000  # bytes of cartridge RAM a new type has: its OBJECT (44 bytes, at 0), then its PDATA (at 48)
FIELDS = ("records", "size", "count", "body", "used", "name", "name_len", "host", "names", "entry", "label_len",
          "setup", "ring", "node", "next", "prev", "panel", "making", "ring_node", "offered")


def heads_h(cfg):
    """game.json heads as SAT_HEADS: {"records": the robots' records, "size": a record's bytes, "count": the records,
    "body": the type field's offset (a word), "used": the in-use byte's, "name": the name's, "name_len": its bytes,
    "host": the original type the new ones stand on in the game's data (its part is the one part_choice changes),
    "names": the types' table, "entry": its entry's bytes (the name first), "label_len": the name's bytes there,
    "setup": the robot's model built (fighter, record), "ring": the part choice's ring (record, ...), "node": a part's
    model copied in (node, OBJECT), "next" / "prev": the part choice's steps (field, available, count, ...), "panel": the
    INFORMATION panel (record, ...), "making": ROBOT MAKING (record), "ring_node": the ring's own part copy (node,
    OBJECT), "offered": the types offered added up, for the panel's count (n, offered), "file": the game's save file, "types": [[the name
    shown, part_choice's version], ...] in order after the game's last type}. part_choice's object is the host's part."""
    hd, pc = cfg.get("heads"), cfg.get("part_choice")
    if not hd:
        return []
    if not pc:
        sys.exit("gen_saturn: heads needs part_choice (the versions it offers)")
    values = {c[0] for c in pc["choices"]}
    for label, value in hd["types"]:
        if value not in values:
            sys.exit(f"gen_saturn: heads type {label} is {value}, which part_choice does not offer")
        if len(label) > int(hd["label_len"]):
            sys.exit(f"gen_saturn: heads type {label} is longer than label_len {hd['label_len']}")
    if len(hd["file"]) != 11:
        sys.exit("gen_saturn: heads file must be the game's 11-character save name")
    body = ", ".join(f"0x{int(str(hd[k]), 0):x}u" for k in FIELDS)
    types = ", ".join(f'{{"{label}", "{value}"}}' for label, value in hd["types"])
    return [
        f"#define SAT_HEADS {{{body}}}",
        f"#define SAT_HEADS_N {len(hd['types'])}",
        f"#define SAT_HEADS_TYPES {{{types}}}",
        f"#define SAT_HEADS_OBJECT 0x{int(str(pc['object']), 0):08x}u",
        f"#define SAT_HEADS_SLOT 0x{SLOT:x}u",
        f'#define SAT_HEADS_FILE "{hd["file"]}"',
    ]


def part_choice_h(pc):
    """game.json part_choice, a model part the player picks (port/saturn/sat_part.c), as C: index 0 is the original."""
    lines = ["/* generated by gen_saturn.py from game.json part_choice: the versions of a model part (sat_part.c) */"]
    if not pc:
        return "\n".join(lines + ["#define SAT_PART_N 0", ""])
    ch = pc["choices"]
    lines += [
        f"#define SAT_PART_N {len(ch) + 1}",
        f"#define SAT_PART_TITLE {json.dumps(pc['title'])}",
        f"#define SAT_PART_OBJECT 0x{int(pc['object'], 0):08x}u",
        f"#define SAT_PART_PDATA 0x{int(pc['pdata'], 0):08x}u",
        f"#define SAT_PART_POINTS {int(pc['points'])}u",
        f"#define SAT_PART_POLYS {int(pc['polygons'])}u",
        f"#define SAT_PART_DROP {int(pc['drop_points'])}u",
        "static const char *const sat_part_labels[] = {" + ", ".join(json.dumps(x) for x in [pc["original"]] + [c[1] for c in ch]) + "};",
        "static const char *const sat_part_values[] = {" + ", ".join(json.dumps(x) for x in ["original"] + [c[0] for c in ch]) + "};",
    ]
    for i, (name, _, b64) in enumerate(ch, 1):
        data = base64.b64decode(b64)
        # the game copies and transforms every point of a part, and too many overrun it (Robo Pit: 450 crashed, 354
        # runs); max_points is the most a game has been shown to take
        points = int(pc["points"]) - int(pc["drop_points"]) + struct.unpack_from(">H", data, 2)[0]
        if "max_points" in pc and points > int(pc["max_points"]):
            sys.exit(f"gen_saturn: part_choice {name} has {points} points, more than max_points {pc['max_points']}")
        rows = [",".join(str(x) for x in data[k:k + 32]) for k in range(0, len(data), 32)]
        lines.append(f"static const unsigned char sat_part_e{i}[] = {{\n" + ",\n".join(rows) + "};")
    lines.append("static const unsigned char *const sat_part_edits[] = {0, " + ", ".join(f"sat_part_e{i}" for i in range(1, len(ch) + 1)) + "};")
    return "\n".join(lines + [""])
