"""A game function's name used as a value in readable C is its guest address in the port, as in the judge.

The judge's game.h (core/readable.game_h with verify_self) defines every callee as its guest address, so a function
name used as a value (stored, masked with MIRROR_PTR, compared, passed, put in a table) is 0x8c...... there and the
judge compares it with what the original stores. The port's game.h declares the host functions, so the same text gave
the host address: `obj->update = OBJ_UPDATE_MIRROR(Some_Update)` stored the host body's address masked to 29 bits
where the original stores the function's 0x0c...... mirror address (found 2026-11-06). gen_port compiles, for each readable file that uses a
function name as a value, a copy in <out>/fnv/ (a #line keeps the original's name in diagnostics) in which only those
uses (with a unary &) read RDV_Name, `#define RDV_Name ((T (*)(P))0xADDRu)` in include/fn_values.h, as the judge's
game.h defines a callee; every call stays a direct host call. A macro of a readable header (reached from types.h)
whose body uses one is redefined there the same way, and game.h includes fn_values.h last; a macro that is only a function's name is read as that name. A call through the
stored value goes through the dispatch table and its thunks, as a call through a pointer translator C stored does.
A value use in a header outside a macro, or one a macro body ends on, is only reported (gen_report.txt notes).

Nearest existing: gen_port.wrap_defines - its per-file Name=Wrapper renames every use of a name, calls included; a
value use must change while the calls stay direct (and gen_port.py is at the 400-line limit).
"""
import pathlib
import re

TOKEN = re.compile(r"//[^\n]*|/\*.*?\*/|\"(?:\\.|[^\"\\\n])*\"|'(?:\\.|[^'\\\n])*'|[A-Za-z_]\w*|\\\n|\S", re.S)
QUIET = ("//", "/*", '"', "'", "\\")  # comments, strings, character constants, line continuations
DIRECTIVE = {"define", "undef", "ifdef", "ifndef", "defined"}
DEFINE = re.compile(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)(\([^)]*\))?((?:[^\n\\]|\\.|\\\n)*)", re.M)
INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]+"([^"]+)"', re.M)
HEAD = "/* Generated by port/tools/gen_port.py (fn_values.py): a function name readable C uses as a value is its guest address. */"


def value_spans(text, names):
    """[(start, end, token)] of each token of names (a set or {token: function}) in text used as a value: not called
    (`Name(`, `(Name)(`, `((T)Name)(`), not a member (`.Name`, `->Name`), not a preprocessor name, outside comments,
    strings and character constants. A unary & before it is part of the span (`&Name` is the same value)."""
    code = [(m.start(), m.end(), m.group()) for m in TOKEN.finditer(text) if not m.group().startswith(QUIET)]
    word = lambda i: code[i][2] if 0 <= i < len(code) else ""  # noqa: E731
    out = []
    for i, (s, e, w) in enumerate(code):
        if w not in names or word(i + 1) == "(" or word(i - 1) == "." or word(i - 1) in DIRECTIVE:
            continue
        if (word(i - 1) == ">" and word(i - 2) == "-" and code[i - 2][1] == code[i - 1][0]) or (
                word(i + 1) == ")" and word(i + 2) == "("):  # (Name)(...), ((T)Name)(...): a call
            continue
        if word(i - 1) == "&" and not (word(i - 2) == "&" and code[i - 2][1] == code[i - 1][0]):
            s = code[i - 1][0]  # unary & (a function is no operand of a bitwise &), not `a && Name`
        out.append((s, e, w))
    return out


def rewrite(text, names, spans=None):
    """(text with each value use as RDV_<its function>, the functions rewritten). names: {token: function}."""
    out, at, got = [], 0, set()
    for s, e, w in value_spans(text, names) if spans is None else spans:
        out += [text[at:s], f"RDV_{names[w]}"]
        at = e
        got.add(names[w])
    return "".join(out + [text[at:]]), got


def no_comments(text):
    """text with each comment a space (its newlines kept, so a comment never joins or ends a directive)."""
    def blank(m):
        return ("\n" * m.group().count("\n") or " ") if m.group().startswith(("//", "/*")) else m.group()
    return TOKEN.sub(blank, text)


def headers(include):
    """The readable headers game.h reaches (types.h and what it includes, quoted, from the include folder)."""
    seen, todo = [], ["types.h"]
    while todo:
        h = todo.pop(0)
        p = include / h
        if h in seen or not p.is_file():
            continue
        seen.append(h)
        todo += INCLUDE.findall(p.read_text(encoding="utf-8", errors="replace"))
    return seen


def header_macros(include, names):
    """([#undef/#define lines], functions used, {alias macro: function}, notes) over the headers game.h reaches. A
    macro that is only a function's name (`#define GRID_INSERT_OBJECT GridNode_InsertLinks`) is an alias: the
    readable files' uses of it are read like the name's. Any other macro whose body uses a name as a value is
    redefined with RDV_name, except a use the body ends on (its user may call it: a note). A value use outside a
    macro is a note. names: {token: function}."""
    lines, used, alias, notes = [], set(), {}, []
    for h in headers(include):
        text = no_comments((include / h).read_text(encoding="utf-8", errors="replace"))
        for m in DEFINE.finditer(text):
            name, params, body = m.group(1), m.group(2) or "", m.group(3).replace("\\\n", " ")
            if not params and body.strip() in names:
                alias[name] = names[body.strip()]
                continue
            own = {k: v for k, v in names.items() if k not in set(re.findall(r"\w+", params))}
            spans = value_spans(body, own)
            notes += [f"{h}: macro {name} ends on {w}: its user may call it (not rewritten)"
                      for _, e, w in spans if not body[e:].strip()]
            spans = [x for x in spans if body[x[1]:].strip()]
            if spans:
                body, got = rewrite(body, own, spans)
                lines += [f"#undef {name}", f"#define {name}{params} {' '.join(body.split())}"]
                used |= got
        rest = DEFINE.sub(lambda m: "\n" * m.group().count("\n"), text)
        notes += [f"{h}: {w} used as a value outside a macro (not rewritten)" for _, _, w in value_spans(rest, names)]
    return lines, used, alias, notes


class Sources:
    """The readable source folder as gen_port's file lists see it: src / "ADDR.c" is the fnv/ copy where there is one."""

    def __init__(self, src, copies):
        self.src, self.copies = pathlib.Path(src), copies

    def __truediv__(self, name):
        return self.copies.get(name, self.src / name)

    def __fspath__(self):
        return str(self.src)

    def as_posix(self):
        return self.src.as_posix()


def tail(game_h):
    """The port's game.h with fn_values.h included last (after types.h's headers, whose macros it may redefine)."""
    head, end = game_h.rsplit("#endif", 1)
    return f'{head}#include "fn_values.h"  /* function names used as values: guest addresses (fn_values.py) */\n#endif{end}'


def write(out, readable, files, protos, names, write_if_changed, notes):
    """Write include/fn_values.h and fnv/ADDR.c for the readable files that use a function name as a value; return
    Sources over readable.SRC with those copies. A summary goes first in notes, the header notes after it.
    names, protos: {addr: name}, {addr: prototype} of every function the port's game.h declares."""
    by_name = {n: x for x, n in names.items()}
    lines, used, alias, hnotes = header_macros(readable.INCLUDE, {n: n for n in by_name})
    tokens = {n: n for n in by_name} | {a: n for a, n in alias.items() if a not in by_name}
    (out / "fnv").mkdir(exist_ok=True)
    copies, uses = {}, 0
    for x in files:
        src = readable.SRC / f"{x}.c"
        original = src.read_text(encoding="utf-8")
        spans = value_spans(original, tokens)
        if spans:
            text, got = rewrite(original, tokens, spans)
            copies[f"{x}.c"] = out / "fnv" / f"{x}.c"
            write_if_changed(copies[f"{x}.c"], f'#line 1 "{src.as_posix()}"\n{text}')
            used |= got
            uses += len(spans)
    for old in (out / "fnv").glob("*.c"):
        if old.name not in copies:
            old.unlink()
    rdv = [f"#define RDV_{n} (({readable.fn_pointer_type(protos[by_name[n]])})0x{by_name[n]}u)" for n in sorted(used)]
    write_if_changed(out / "include" / "fn_values.h", "\n".join(
        [HEAD, "#ifndef FN_VALUES_H", "#define FN_VALUES_H", *rdv, *lines, "#endif", ""]))
    notes[:0] = [f"function names used as values (guest addresses, fn_values.py): {uses} uses in {len(copies)} "
                 f"readable files, {len(lines) // 2} header macros, {len(alias)} alias macros, {len(used)} functions",
                 *hnotes]
    return Sources(readable.SRC, copies)
