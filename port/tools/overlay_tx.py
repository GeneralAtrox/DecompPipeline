"""Translator C for an overlay workspace (gen_overlays.py's worker; tools/tx_port.py, as gen_port.py's for main): which
judged functions a unit compiles, their files, and the tc_call glue the loaded unit answers with (overlay.h
overlay_glue), and the stub that sends a "native" function to the game's own C. Runs inside the worker's process,
after gen_port.load_core."""
import re

import gen_port
import overlay_slots
import tx_port


def pick(reg, readable, paths, tx_dir, tx_mode, files, inr, prefix, rebase=(), rebase_dir=None):
    """(files, txs, texts, why): tx_port.pick's readable files and translated functions in the unit's ranges (inr),
    the translated texts with the unit's prefix, and why each judged function in range is not used. As
    gen_port.translator_c for main: the host C runtime's names stay the host's. rebase: the slot units' canonical
    ranges (tx_port.inbound)."""
    from core import lookalike, readable_abi  # noqa: E402
    ok, why = tx_port.judged(tx_dir)
    ok = {x: f for x, f in ok.items() if inr(x)}
    why = {x: w for x, w in why.items() if inr(x)}
    crt = {x for x, e in reg.functions.items() if readable.parse_proto(e["proto"])[1] in gen_port.CRT}
    texts, glue_why = tx_port.inbound(reg, readable_abi, paths, ok, crt, prefix)
    overlay_slots.rebased(texts, ok, rebase, rebase_dir)
    why.update(glue_why)
    sq = {a for a in texts if tx_port.store_queues(ok[a].read_text(encoding="utf-8"))}
    files, txs = tx_port.pick(tx_mode, files, lookalike.readable_sources(paths.ROOT), texts, crt, sq)
    return files, txs, texts, why


def write(d, reg, prefix, txs, texts, protos, metas, names, why, readable=()):
    """Writes <d>/tx/ and <d>/txglue.c; returns (the tx files, the addresses with glue). readable: the unit's readable
    files, which translator C calls too: by argument words a helper's r0..r3 or a float would arrive wrong. A function
    whose glue cannot be made goes into why (tc_call's word call takes it, as for main)."""
    from core import readable_abi  # noqa: E402
    files = [str(f) for f in tx_port.write(d, {x: texts[x] for x in txs}, gen_port.write_if_changed)]
    glue = []
    for x in sorted({*txs, *readable}):
        kept = x in texts and x in txs and tx_port.KEPT in texts[x].split("\n", 1)[0]
        try:
            glue.append((x, tx_port.outbound_glue(reg, readable_abi, x, protos[x], metas[x], names[x], None, kept),
                         names[x]))
        except Exception as e:  # noqa: BLE001
            why[x] = f"tc_call glue: {str(e)[:160]}"
    gen_port.write_if_changed(d / "txglue.c", glue_c(prefix, glue))
    return files, [x for x, _, _ in glue]


def glue_c(prefix, rows):
    """txglue.c: rows [(addr, glue lines (tx_port.outbound_glue), name)] and the table overlay_table.c points at."""
    out = [f"/* Generated by port/tools/gen_overlays.py: workspace {prefix}'s tc_call glue (overlay.h overlay_glue). */",
           '#include "game.h"', '#include "tx_rt.h"', '#include "port_dispatch.h"', ""]
    for _, g, _ in rows:
        out += g
    out += ["", f"const PortDispatch {prefix}__txglue[] = {{"]
    out += [f'    {{0x{a}u, (PortFn)g_{a}, "{n}"}},' for a, _, n in rows] or ["    {0, 0, 0},"]
    return "\n".join(out + ["};"]) + "\n"


def native_c(readable, proto, cname, r0=False):
    """stubs.c's body for a native function (overlays.json "native", or "wrap"): the function, under its registry
    prototype, calls the game's own C, cname, which takes the same arguments. r0: the function is wrapped translator C
    that returns its body's r0 where the registry returns nothing (tx_port.KEPT), so both return u32 and pass it on."""
    ret, name, params = readable.parse_proto(proto)
    if readable.is_variadic(proto):
        raise ValueError(f"native {cname}: {name} is variadic")
    if r0:
        ret, proto = "u32", re.sub(rf"^.*?(?=\b{re.escape(name)}\s*\()", "u32 ", proto.strip(), count=1)
    decl = re.sub(rf"\b{re.escape(name)}(?=\s*\()", cname, proto.strip().rstrip(";"), count=1)
    call = f"{cname}({', '.join(p for _, p in params)});"
    return [decl + ";", proto.strip().rstrip(";"), "{", "    " + ("" if ret.strip() == "void" else "return ") + call,
            "}"]


def kept_stub(readable, prefix, proto, cname):
    """A wrapped function's stub when its translator C returns the body's r0 where the registry returns nothing
    (tx_port.KEPT): native_c's u32 body under the prefixed name, for the end of that translator C. It cannot go in
    stubs.c, where the workspace's game.h declares the function void; translator C is compiled without game.h and
    prefix.h."""
    name = readable.parse_proto(proto)[1]
    return native_c(readable, re.sub(rf"\b{re.escape(name)}(?=\s*\()", f"{prefix}__{name}", proto.strip(), count=1),
                    cname, True)


def wrap(d, wraps, prefix, names, files, txs, texts, src, err):
    """overlays.json "wrap" {addr: C name}: the function stays compiled, renamed <C name>_Original, and its stub
    (native_c) calls the C name instead. Translator C is renamed in its text; a readable file compiles through
    <d>/wrap/<addr>.c, which renames it and includes it. Returns ({addr: that file}, the translator C ones that return
    their body's r0)."""
    out, kept = {}, set()
    for x, c in sorted(wraps.items()):
        old = f"{prefix}__{names[x]}("
        if x in txs and old in texts[x]:
            texts[x] = texts[x].replace(old, f"{c}_Original(")
            kept |= {x} if tx_port.KEPT in texts[x].split("\n", 1)[0] else set()
        elif x in files:
            (d / "wrap").mkdir(exist_ok=True)
            f = d / "wrap" / f"{x}.c"
            gen_port.write_if_changed(f, f"/* Generated by port/tools/gen_overlays.py: {x}.c, its {names[x]} renamed "
                                         f"{c}_Original (overlays.json wrap). */\n#undef {names[x]}\n"
                                         f"#define {names[x]} {c}_Original\n#include \"{(src / f'{x}.c').as_posix()}\"\n")
            out[x] = str(f)
        else:
            raise err(f"{prefix}: wrap {x}: neither its readable file nor its translator C is compiled")
    return out, kept


def stubs_c(readable, prefix, stubs, protos, native, bare):
    """<prefix>/stubs.c: a logging stub for each function in stubs and each bare catalog start, and native_c's body
    for each native or wrapped function {addr: C name} (not the wrapped ones kept_stub writes)."""
    body = ["/* Generated by port/tools/gen_overlays.py: logging stubs. */", '#include "game.h"',
            '#include "port_stub.h"', ""]
    for x in stubs:
        body += gen_port.stub_c(readable, x, protos[x]) + [""]
    for x, c in sorted(native.items()):
        body += native_c(readable, protos[x], c) + [""]
    body += [f'u32 {prefix}__fn_{x}(void) {{ port_stub(0x{x}u, "fn_{x}"); return 0; }}' for x in bare]
    return "\n".join(body) + "\n"
