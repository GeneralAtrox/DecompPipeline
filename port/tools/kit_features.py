"""The Dreamcast kit's feature list, generated from its source: every SDK function the kit's SDK modules define
(port/sdk/*.c, the names a game.json "sdk" entry brings in), by module. Never kept by hand: it is read from the C each
time (tools/AutoOnboard/onboard_gaps.py calls features() on the checkout it runs from), so it cannot go stale; `--out FILE`
publishes the same JSON for anyone without DP.

    python port/tools/kit_features.py [--out FILE]

A definition is a line starting a non-static function (return type, name, parameters) whose body opens on that line
or the next; prototypes, statics, macros and the module's private helpers named with a leading underscore or `sdk_`
are left out. What it does not list: hardware the kit models (port/pvr, runtime/aica*: a register-level model, not a
list of calls), and a game's own replacements (its game.json "sources" and "hardware").

Nearest existing: port/tools/contract_sdk.py - the contract's prose per SDK module (what it replaces, what it needs
from game.h), hand-written for port/CONTRACT.md; it names families ("Shinobi system services"), not the functions a
game's calls can be checked against.
"""
import argparse
import json
import pathlib
import re

KIT = pathlib.Path(__file__).resolve().parents[1]
DEF = re.compile(r"^(?!static\b|typedef\b|extern\b|#|\s)[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\(([^;{}()]|\([^()]*\))*\)"
                 r"\s*\{", re.M)


def features(kit=KIT):
    """{"console", "source", "modules": {module: [names]}, "names": {name: module}} from kit/sdk/*.c."""
    mods = {}
    for c in sorted((pathlib.Path(kit) / "sdk").glob("*.c")):
        text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), c.read_text(encoding="utf-8",
                                                                                         errors="replace"), flags=re.S)
        names = sorted({m.group(1) for m in DEF.finditer(text)
                        if not m.group(1).startswith(("_", "sdk_")) and m.group(1) not in ("if", "while", "for",
                                                                                            "switch", "return")})
        if names:
            mods[c.stem] = names
    return {"console": "dreamcast", "source": "port/sdk/*.c (generated by port/tools/kit_features.py)",
            "modules": mods, "names": {n: m for m, ns in mods.items() for n in ns}}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    f = features()
    text = json.dumps(f, indent=1) + "\n"
    if a.out:
        pathlib.Path(a.out).write_text(text, encoding="utf-8", newline="\n")
        print(f"{len(f['names'])} functions in {len(f['modules'])} modules -> {a.out}")
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
