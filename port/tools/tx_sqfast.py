"""The store-queue helpers of a translated function, a whole block at a time (game.json sq_fast, build.py --sq-fast).

The judged C carries the helpers of targets/dreamcast_sh4/translator/sh4translate/sqmodel.py, which walk a block byte by
byte; in a game that draws through them they are a fifth of a tick (docs/RUNTIME_TARGET.md). For a play build this writes a copy of each such file
into the generated folder with sq_put and sq_pref swapped for the versions below and the wrapper including the copy. The
judged file is not touched, nothing else in the copy changes, and without the switch the build includes the judged file.
tests/test_sq_fast.py runs both versions through the same random stores and sends: queues and RAM stay equal.

Nearest existing: tx_port.py - writes the wrappers this edits, but it is the judge's way in and sits at the 400-line cap.
"""
import re

# Both helpers keep sqmodel.py's meaning for every address. Only a store wholly inside one block of the window takes
# the short way, and a send only ever touches two blocks of 0x8c000000.., which are RAM, whole and 32-byte aligned.
FAST = {
    "sq_put": r"""static __forceinline void sq_put(SqQueues *q, u32 a, u32 n, u32 v)
{
    u32 o = a & 31u, k = (a >> 5) & 1u, i;
    if (sq_in(a) && sq_in(a + n - 1u) && o + n <= 32u) {
        q->marked[k] |= ((1u << n) - 1u) << o;
        if (n == 4u) *(u32 *)(q->bytes[k] + o) = v;
        else if (n == 2u) *(u16 *)(q->bytes[k] + o) = (u16)v;
        else q->bytes[k][o] = (u8)v;
        return;
    }
    for (i = 0; i < n; i++)
        if (sq_in(a + i)) {
            q->marked[((a + i) >> 5) & 1u] |= 1u << ((a + i) & 31u);
            q->bytes[((a + i) >> 5) & 1u][(a + i) & 31u] = (u8)(v >> (8u * i));
        }
}""",
    "sq_pref": r"""static void sq_pref(SqQueues *q, u32 a)
{
    u32 k, to, from, m, w, j;
    u32 *d, *s;
    const u32 *g;
    if (!sq_in(a)) return;
    k = (a >> 5) & 1u;
    to = 0x8c000000u | (a & 0x00ffffe0u);
    from = q->from[k] ? q->from[k] : to;
    m = q->marked[k];
    d = SQ_HOST(to);
    s = SQ_HOST(from);
    g = (const u32 *)q->bytes[k];
    for (w = 0; w < 8u; w++) {
        u32 nib = (m >> (w * 4u)) & 15u;
        if (nib == 15u) d[w] = g[w];
        else if (from != to) {
            u32 v = s[w];
            for (j = 0; j < 4u; j++)
                if ((nib >> j) & 1u) v = (v & ~(0xffu << (8u * j))) | ((u32)q->bytes[k][w * 4u + j] << (8u * j));
            d[w] = v;
        } else if (nib)
            for (j = 0; j < 4u; j++)
                if ((nib >> j) & 1u) ((u8 *)d)[w * 4u + j] = q->bytes[k][w * 4u + j];
    }
    q->from[k] = to;
    q->marked[k] = 0;
}""",
}
# A function whose mocked callees stored into the queues (sqmodel.sq_callee_helpers) carries src: for each queue byte the
# RAM byte a callee stored it from. A store clears its bytes' src; a send takes a byte with one from that RAM byte, and
# leaves it unwritten when that is the byte it sends to. A block with any src is sent byte by byte as the judged helper
# does (all bytes read before any is written); one without takes the block-at-a-time way above.
CALLEE = {
    "sq_put": FAST["sq_put"].replace(
        "        else q->bytes[k][o] = (u8)v;\n        return;",
        "        else q->bytes[k][o] = (u8)v;\n        for (i = 0; i < n; i++) q->src[k][o + i] = 0;\n        return;").replace(
        "            q->bytes[((a + i) >> 5) & 1u][(a + i) & 31u] = (u8)(v >> (8u * i));\n",
        "            q->bytes[((a + i) >> 5) & 1u][(a + i) & 31u] = (u8)(v >> (8u * i));\n"
        "            q->src[((a + i) >> 5) & 1u][(a + i) & 31u] = 0;\n"),
    "sq_pref": FAST["sq_pref"].replace(
        "    g = (const u32 *)q->bytes[k];\n",
        r"""    g = (const u32 *)q->bytes[k];
    for (j = 0; j < 32u && !q->src[k][j]; j++)
        ;
    if (j < 32u) {
        u8 b[32], *d8 = (u8 *)d;
        const u8 *s8 = (const u8 *)s;
        for (j = 0; j < 32u; j++) {
            u32 c = q->src[k][j];
            b[j] = ((m >> j) & 1u) ? q->bytes[k][j] : c ? (c != to + j ? *((const u8 *)SQ_HOST(c & ~3u) + (c & 3u)) : 0)
                 : from != to ? s8[j] : 0;
        }
        for (j = 0; j < 32u; j++)
            if (((m >> j) & 1u) || (q->src[k][j] ? q->src[k][j] != to + j : from != to)) d8[j] = b[j];
        for (j = 0; j < 32u; j++) q->src[k][j] = 0;
        q->from[k] = to;
        q->marked[k] = 0;
        return;
    }
"""),
}
SRC = re.compile(r"\bsrc\s*\[\s*2\s*\]\s*\[\s*32\s*\]")
INLINE = ("sq_wr32", "sq_wrf32")  # the stores a vertex is made of: a call each would cost what the loop did
HEAD = """/* Generated by port/tools/tx_sqfast.py: the judged C with sq_put and sq_pref a block at a time. */
#ifndef SQ_HOST
#define SQ_HOST(a) ((u32 *)(uintptr_t)(a))
#endif
"""
INCLUDE = re.compile(r'#include "([^"]+\.c)"')


def helper_span(text, name):
    """(start, end) of `static void name(...) {...}` in the C text, spaces or none (the judged files are minified)."""
    m = re.search(r"static\s+void\s+" + name + r"\s*\(\s*SqQueues\s*\*", text)
    if not m:
        return None
    depth, at = 0, text.index("{", m.end())
    for i in range(at, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if not depth:
            return m.start(), i + 1
    return None


def rewrite(text):
    """The C with the helpers swapped, or None if it does not carry them all."""
    for name, fast in (CALLEE if SRC.search(text) else FAST).items():
        span = helper_span(text, name)
        if not span:
            return None
        text = text[:span[0]] + fast + text[span[1]:]
    for name in INLINE:
        text, n = re.subn(r"static\s+void\s+" + name + r"\s*\(", f"static __forceinline void {name}(", text)
        if n != 1:
            return None
    return HEAD + text


def apply(tx_texts, out, write_if_changed):
    """Points each wrapper in {addr: text} whose judged file has store queues at a rewritten copy; returns how many."""
    done = 0
    for addr, wrapper in tx_texts.items():
        m = INCLUDE.search(wrapper)
        if not m:
            continue
        with open(m.group(1), encoding="utf-8") as f:
            text = f.read()
        if "SqQueues" not in text:
            continue
        fast = rewrite(text)
        if fast is None:
            raise SystemExit(f"sq_fast: {addr} carries store queues this tool does not recognise ({m.group(1)})")
        copy = out / "tx_sq" / f"{addr}.c"
        copy.parent.mkdir(parents=True, exist_ok=True)
        write_if_changed(copy, fast)
        tx_texts[addr] = wrapper[:m.start(1)] + copy.as_posix() + wrapper[m.end(1):]
        done += 1
    return done
